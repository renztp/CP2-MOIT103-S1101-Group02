    private void loadEmployeeTable() {

    try {

        FileHandler fileHandler = new FileHandler();

        String[][] employees =
                fileHandler.getEmployeesRecords();

        DefaultTableModel model =
                (DefaultTableModel) tblEmployees.getModel();

        // clear old rows
        model.setRowCount(0);

        for (String[] emp : employees) {

            model.addRow(new Object[] {

                emp[0], // Employee Number
                emp[1], // Last Name
                emp[2], // First Name
                emp[6], // SSS
                emp[7], // PhilHealth
                emp[8], // TIN
                emp[9]  // Pag-IBIG

            });
        }

    } catch (IOException e) {

        e.printStackTrace();

    }
}

