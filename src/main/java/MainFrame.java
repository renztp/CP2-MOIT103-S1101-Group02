    private void btnAddEmployeeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddEmployeeActionPerformed
      
   String empNo =
            JOptionPane.showInputDialog("Enter Employee Number:");

    String lastName =
            JOptionPane.showInputDialog("Enter Last Name:");

    String firstName =
            JOptionPane.showInputDialog("Enter First Name:");

    String sss =
            JOptionPane.showInputDialog("Enter SSS Number:");

    String philHealth =
            JOptionPane.showInputDialog("Enter PhilHealth Number:");

    String tin =
            JOptionPane.showInputDialog("Enter TIN:");

    String pagIbig =
            JOptionPane.showInputDialog("Enter Pag-IBIG Number:");

    // Validation
    if (empNo.isEmpty()
            || lastName.isEmpty()
            || firstName.isEmpty()) {

        JOptionPane.showMessageDialog(

                this,

                "Required fields cannot be empty.",

                "Validation Error",

                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    DefaultTableModel model =
            (DefaultTableModel) tblEmployees.getModel();

    // Duplicate check
    for (int i = 0; i < model.getRowCount(); i++) {

        String existingEmpNo =
                model.getValueAt(i, 0).toString();

        if (existingEmpNo.equals(empNo)) {

            JOptionPane.showMessageDialog(

                    this,

                    "Employee Number already exists.",

                    "Duplicate Error",

                    JOptionPane.ERROR_MESSAGE
            );

            return;
        }
    }

    try {

        FileHandler fileHandler = new FileHandler();

        fileHandler.addEmployeeRecord(

                empNo,
                lastName,
                firstName,
                sss,
                philHealth,
                tin,
                pagIbig
        );

        // Add row to JTable immediately
        model.addRow(new Object[] {

            empNo,
            lastName,
            firstName,
            sss,
            philHealth,
            tin,
            pagIbig
        });

        JOptionPane.showMessageDialog(

                this,

                "Employee added successfully."

        );

    } catch (IOException e) {

        JOptionPane.showMessageDialog(

                this,

                "Error saving employee.",

                "File Error",

                JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_btnAddEmployeeActionPerformed

